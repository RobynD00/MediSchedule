import 'package:flutter/material.dart';
import 'package:medischedule/core/application_widget.dart';
import 'package:medischedule/screens/medications/medication.dart';

// The NotificationScreen class displays a list of upcoming medication reminders and provides a user interface for managing them. It shows the next scheduled dose across all medications and allows users to view details about the medication, including its name, dose, and scheduled time. The screen also includes a feedback banner to inform users about their next reminder or the absence of scheduled reminders.
class NotificationScreen extends StatelessWidget {
  //static const routeName = '/notifications';
  final List<Medication> medications;
  final DateTime Function()? clock;

  // Creates a new NotificationScreen with the given list of medications and an optional clock function for testing purposes. The medications parameter is required and represents the list of medications to be displayed in the notification screen. The clock parameter allows for injecting a custom clock function for testing, defaulting to the current system time if not provided.
  const NotificationScreen({
    this.medications = const [],
    this.clock,
    super.key,
  });

  DateTime get timeNow => clock?.call() ?? DateTime.now();

  // Builds the notification screen UI, displaying upcoming medication reminders and relevant information. It shows the next scheduled dose across all medications and provides a feedback banner to inform users about their next reminder or the absence of scheduled reminders.
  @override
  Widget build(BuildContext context) {
    final now = timeNow;
    // The upcoming list is generated by iterating through the provided medications and checking if each medication has a next scheduled dose using the nextDoseAt method. If a next dose exists, it is added to the upcoming list as a _ScheduledMedication instance, which includes the medication and its scheduled time. The list is then sorted by the scheduled time to ensure that the earliest upcoming dose is displayed first.
    final upcoming = <ScheduledMedication>[
      for (final medication in medications)
        if (medication.nextDoseAt(now) case final nextDose?)
          ScheduledMedication(medication, nextDose),
    ]..sort((a, b) => a.time.compareTo(b.time));

    final nextReminder = upcoming.isEmpty ? null : upcoming.first;

    // The notification screen UI is built using a Scaffold widget, which provides the basic structure for the screen, including an AppBar and a ListView to display the content. The AppBar contains the title "Notifications," and the ListView displays a feedback banner with information about the next scheduled reminder or a message indicating that there are no scheduled reminders. If there is a next reminder, it is displayed in an AppCard widget, showing the medication name, dose, and scheduled time.
    return Scaffold(
      appBar: AppBar(title: const Text('Notifications')),
      body: ListView(
        padding: const EdgeInsets.all(20),
        children: [
          ApplicationFeedbackBannerWidget(
            message: nextReminder == null
                ? 'No scheduled medication reminders yet.'
                : 'Your next reminder is ${nextReminder.medication.name} at ${formatTime(context, nextReminder.time)}.',
            icon: Icons.notifications_active_outlined,
          ),

          const SizedBox(height: 20),
          if (nextReminder != null)
            ApplicationCardWidget(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    nextReminder.medication.name,
                    style: Theme.of(context).textTheme.titleLarge,
                  ),
                  const SizedBox(height: 6),
                  Text(
                    '${nextReminder.medication.dose} · ${formatDateTime(context, nextReminder.time)}',
                  ),
                ],
              ),
            ),
        ],
      ),
    );
  }

  // Formats the given time as a localized string for display in the notification screen. It uses the MaterialLocalizations class to format the time according to the user's locale and preferences, ensuring that the displayed time is clear and understandable.
  String formatTime(BuildContext context, DateTime time) {
    return MaterialLocalizations.of(context)
        .formatTimeOfDay(TimeOfDay.fromDateTime(time));
  }

  // Formats the given date and time as a localized string for display in the notification screen. It checks if the date is the same as the current date and displays "Today" if it is, or formats the date using the MaterialLocalizations class for other dates. The formatted string includes both the date and time for clarity.
  String formatDateTime(BuildContext context, DateTime time) {
    final date = DateUtils.isSameDay(time, timeNow)
        ? 'Today'
        : MaterialLocalizations.of(context).formatMediumDate(time);
    return '$date, ${formatTime(context, time)}';
  }
}

// The showNoticationScreen function displays a dialog to remind the user about a scheduled medication dose. It takes the context, medication details, scheduled time, and optional callbacks for when the user indicates that they have taken, snoozed, or skipped the medication. The dialog presents the medication information and provides buttons for the user to respond to the reminder. The function returns a Future<bool?> indicating whether the user has taken the medication (true), snoozed it (false), or skipped it (false).
Future<bool?> showNoticationScreen(
  BuildContext context, {
  required Medication medication,
  required DateTime scheduledAt,
  bool isTest = false,
  VoidCallback? onTaken,
  VoidCallback? onSnoozed,
  VoidCallback? onSkipped,
}) {
  return showDialog<bool>(
    context: context,
    builder: (dialogContext) {
      final colorScheme = Theme.of(dialogContext).colorScheme;
      final scheduledTime = MaterialLocalizations.of(dialogContext)
          .formatTimeOfDay(TimeOfDay.fromDateTime(scheduledAt));
      // The dialog is built using a Dialog widget, which provides a modal window for displaying the medication reminder. It includes an icon representing notifications, the medication name and dose, the scheduled time, and buttons for the user to indicate whether they have taken, snoozed, or skipped the medication. The dialog is styled with padding, colors, and text styles to create a visually appealing and user-friendly interface.
      return Dialog(
        insetPadding: const EdgeInsets.symmetric(horizontal: 24, vertical: 28),
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 360),
          child: SingleChildScrollView(
            padding: const EdgeInsets.fromLTRB(24, 24, 24, 20),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                Icon(
                  Icons.notifications_active,
                  size: 58,
                  color: colorScheme.primary,
                ),
                // The SizedBox widget is used to create vertical spacing between the notification icon and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 16),
                Text(
                  isTest ? 'Test reminder' : 'Medication reminder',
                  style: Theme.of(dialogContext).textTheme.titleMedium,
                ),
                // The SizedBox widget is used to create vertical spacing between the title and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 12),
                Container(
                  width: 128,
                  height: 112,
                  alignment: Alignment.center,
                  decoration: BoxDecoration(
                    color: colorScheme.surfaceContainerHighest,
                    border: Border.all(color: colorScheme.outlineVariant),
                  ),
                  child: Icon(
                    medication.icon,
                    size: 56,
                    color: colorScheme.primary,
                  ),
                ),
                // The SizedBox widget is used to create vertical spacing between the medication icon and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 18),
                Text(
                  medication.name,
                  textAlign: TextAlign.center,
                  style: Theme.of(dialogContext).textTheme.titleLarge,
                ),
                // The SizedBox widget is used to create vertical spacing between the medication name and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 6),
                Text(
                  '${medication.dose} · Scheduled for $scheduledTime',
                  textAlign: TextAlign.center,
                  style: Theme.of(dialogContext).textTheme.bodyLarge,
                ),
                // The SizedBox widget is used to create vertical spacing between the medication details and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                if (medication.notes.isNotEmpty) ...[
                  const SizedBox(height: 6),
                  Text(
                    medication.notes,
                    textAlign: TextAlign.center,
                    style: Theme.of(dialogContext).textTheme.bodyMedium,
                  ),
                ],
                // The SizedBox widget is used to create vertical spacing between the medication notes and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 20),
                SizedBox(
                  width: double.infinity,
                  child: FilledButton(
                    style: FilledButton.styleFrom(
                      backgroundColor: colorScheme.primary,
                      foregroundColor: colorScheme.onPrimary,
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(5),
                      ),
                      padding: const EdgeInsets.symmetric(vertical: 14),
                    ),
                    onPressed: () {
                      onTaken?.call();
                      Navigator.of(dialogContext).pop(true);
                    },
                    child: const Text('I have taken it'),
                  ),
                ),
                // The SizedBox widget is used to create vertical spacing between the "I have taken it" button and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                const SizedBox(height: 10),
                SizedBox(
                  width: double.infinity,
                  child: FilledButton(
                    style: FilledButton.styleFrom(
                      backgroundColor: colorScheme.secondary,
                      foregroundColor: colorScheme.onSecondary,
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(5),
                      ),
                      padding: const EdgeInsets.symmetric(vertical: 14),
                    ),
                    onPressed: () {
                      onSnoozed?.call();
                      Navigator.of(dialogContext).pop(false);
                    },
                    child: const Text('Remind me later'),
                  ),
                ),
                // The SizedBox widget is used to create vertical spacing between the "Remind me later" button and the subsequent content in the medication reminder popup. It provides a consistent layout and visual separation, enhancing the overall user experience by ensuring that the elements are not crowded together.
                TextButton(
                  onPressed: () {
                    onSkipped?.call();
                    Navigator.of(dialogContext).pop(false);
                  },
                  style: TextButton.styleFrom(
                    foregroundColor: colorScheme.onSurface,
                    textStyle: const TextStyle(
                      decoration: TextDecoration.underline,
                    ),
                  ),
                  child: const Text('Skip the medication'),
                ),
              ],
            ),
          ),
        ),
      );
    },
  );
}

// The ScheduledMedication class represents a scheduled dose of a medication, including the medication itself and the time of the scheduled dose. It is used to track upcoming doses and display them in the notification screen.
class ScheduledMedication {
  const ScheduledMedication(this.medication, this.time);
  final Medication medication;
  final DateTime time;
}
